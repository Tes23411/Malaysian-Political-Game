function toCamelCase(str: string): string {
  const trimmed = str.trim();

  // Special cases that don't map cleanly through the general algorithm
  if (trimmed === 'BUMIPUTERA SABAH(MUSLIM) (%)') return 'bumiputeraSabahMuslimPercent';
  if (trimmed === 'BUMIPUTERA SABAH(NON-MUSLIM) (%)') return 'bumiputeraSabahNonMuslimPercent';
  if (trimmed === 'BUMIPUTERA SARAWAK(MUSLIM) (%)') return 'bumiputeraSarawakMuslimPercent';
  if (trimmed === 'BUMIPUTERA SARAWAK(NON-MUSLIM) (%)') return 'bumiputeraSarawakNonMuslimPercent';
  if (trimmed === 'ORANG ASLI (%)') return 'orangAsliPercent';
  // Fix: header says "(1947)" but enrichDemographicsData expects "...2018"
  if (trimmed === 'URBAN-RURAL CLASSIFICATION (1947)') return 'urbanRuralClassification2018';

  return trimmed
    .toLowerCase()
    // "malay (%)" -> "malay percent"
    .replace(/\s*\(%\)/, ' percent')
    // "classification (1947)" -> "classification"
    .replace(/\s*\([^)]*\)/, '')
    // "malay percent" -> "malayPercent", "unique code" -> "uniqueCode"
    .replace(/[^a-zA-Z0-9]+(.)?/g, (_match, chr) => chr ? chr.toUpperCase() : '');
}

/** Parse a CSV line respecting double-quoted fields (which may contain commas). */
function parseCsvLine(line: string): string[] {
  const fields: string[] = [];
  let current = '';
  let inQuotes = false;

  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') {
      // Escaped quote inside a quoted field ("") -> literal "
      if (inQuotes && line[i + 1] === '"') {
        current += '"';
        i++;
      } else {
        inQuotes = !inQuotes;
      }
    } else if (ch === ',' && !inQuotes) {
      fields.push(current);
      current = '';
    } else {
      current += ch;
    }
  }
  fields.push(current);
  return fields;
}

/** Positional hash so "AB" and "BA" don't collide. */
function hashCode(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash * 31 + str.charCodeAt(i)) >>> 0; // unsigned 32-bit
  }
  return hash;
}

/** Stateful LCG — each call returns an independent draw in [0, 1). */
function makePseudoRng(seed: number): () => number {
  let state = seed;
  return () => {
    state = (state * 9301 + 49297) % 233280;
    return state / 233280;
  };
}

function enrichDemographicsData(data: Demographics[]): Demographics[] {
  return data.map(d => {
    const pseudo = makePseudoRng(hashCode(d.uniqueCode || ''));

    const classification = String(d.urbanRuralClassification2018 || 'SEMI-URBAN').toUpperCase();
    const isUrban = classification.includes('URBAN') && !classification.includes('SEMI');
    const isRural = classification.includes('RURAL');

    const baseIncome = isUrban ? 8500 : isRural ? 3500 : 5500;
    const medianIncome = Math.round((baseIncome * (0.8 + pseudo() * 0.4)) / 100) * 100;

    const baseYouth = isUrban ? 40 : isRural ? 25 : 32;
    const youngVotersPercent = Math.round((baseYouth + (pseudo() * 10 - 5)) * 10) / 10;

    return { ...d, medianIncome, youngVotersPercent };
  });
}

export const loadDemographicsData = async (): Promise<Demographics[]> => {
  try {
    const response = await fetch('./data/demographics.csv');
    if (!response.ok) {
      console.error('Failed to load demographics data');
      return [];
    }
    const csvText = await response.text();
    const lines = csvText.trim().split('\n');
    if (lines.length < 2) return [];

    const headers = parseCsvLine(lines[0]).map(h => toCamelCase(h.trim()));

    const data: Demographics[] = lines.slice(1).map(line => {
      const values = parseCsvLine(line);
      const entry: { [key: string]: string | number } = {};

      headers.forEach((key, index) => {
        if (!key) return;
        const raw = values[index]?.trim() ?? '';
        const num = parseFloat(raw);
        entry[key] = raw === '' || isNaN(num) ? raw : num;
      });

      return entry as unknown as Demographics;
    });

    return enrichDemographicsData(data);
  } catch (error) {
    console.error('Error parsing demographics CSV:', error);
    return [];
  }
};
